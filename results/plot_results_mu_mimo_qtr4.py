"""Plot MU-MIMO qtr4 results aggregated over multiple drops.

This script targets artifacts generated by ``sims/qtr4.sh`` via
``sims/sim_mu_mimo_testing_updates_w_p1.py``.

Expected filename patterns are:

* Prediction:
  ``mu_mimo_results_p1_<p1>_p3_<p3>_rx_UE_<rx>_tx_UE_<tx>_prediction_<method>_pmi_quantization_<q>.npz``
* Non-prediction / perfect-CSI:
  ``mu_mimo_results_p1_<p1>_p3_<p3>_rx_UE_<rx>_tx_UE_<tx>_perfect_CSI_<perfect>_pmi_quantization_<q>.npz``

The script averages metrics across drops and produces:

* Coded BER vs number of RUs (fixed RX UEs)
* Coded BER vs number of RX UEs (fixed RUs)
* Throughput vs number of RUs (fixed RX UEs)
* Throughput vs number of RX UEs (fixed RUs)
"""

from __future__ import annotations

import argparse
from dataclasses import dataclass
from pathlib import Path
from typing import List, Optional, Sequence

import matplotlib.pyplot as plt
import numpy as np
from fractions import Fraction

@dataclass(frozen=True)
class Scenario:
    phase_1_enabled: bool
    phase_3_enabled: bool
    prediction: bool
    quantization: bool
    label: str
    perfect_csi: bool = False
    prediction_method: Optional[str] = None


@dataclass
class DataPoint:
    uncoded_ber: float
    coded_ber: float
    throughput: float

@dataclass(frozen=True)
class MCS:
    mod_order: int
    code_rate: str

    @property
    def file_token(self) -> str:
        return f"mod_order_{self.mod_order}_code_rate_{self.code_rate}"
    
    @property
    def code_rate_variants(self) -> list[str]:
        variants = [str(self.code_rate)]
        try:
            frac = Fraction(str(self.code_rate))
            if frac.denominator != 0:
                decimal_str = str(float(frac))
                if decimal_str not in variants:
                    variants.append(decimal_str)
                frac_str = f"{frac.numerator}/{frac.denominator}"
                if frac_str not in variants:
                    variants.append(frac_str)
        except (ValueError, ZeroDivisionError):
            pass
        return variants


def _scalar_last(data: np.lib.npyio.NpzFile, key: str) -> float:
    arr = np.asarray(data.get(key, []), dtype=float).reshape(-1)
    if arr.size == 0:
        return float("nan")
    return float(arr[-1])


def _nanmean_array(data: np.lib.npyio.NpzFile, key: str) -> float:
    arr = data.get(key)
    if arr is None:
        return float("nan")
    return float(np.nanmean(np.asarray(arr, dtype=float)))


def _build_filename_candidates(
    *,
    rx_ues: int,
    tx_ues: int,
    scenario: Scenario,
    mcs: Optional[MCS] = None,
) -> list[str]:
    p1 = str(scenario.phase_1_enabled)
    p3 = str(scenario.phase_3_enabled)
    quant = str(scenario.quantization)
    mcs_prefixes = [""]
    if mcs:
        mcs_prefixes = [f"mod_order_{mcs.mod_order}_code_rate_{rate}_" for rate in mcs.code_rate_variants]

    filenames: list[str] = []
    for mcs_prefix in mcs_prefixes:
        if scenario.prediction:
            method = scenario.prediction_method or "two_mode"
            filenames.append(
                f"mu_mimo_results_p1_{p1}_p3_{p3}_{mcs_prefix}rx_UE_{rx_ues}_tx_UE_{tx_ues}"
                f"_prediction_{method}_pmi_quantization_{quant}.npz"
            )
            continue
        filenames.append(
            f"mu_mimo_results_p1_{p1}_p3_{p3}_{mcs_prefix}rx_UE_{rx_ues}_tx_UE_{tx_ues}"
            f"_perfect_CSI_{scenario.perfect_csi}_pmi_quantization_{quant}.npz"
        )
    return filenames


def _resolve_result_path(
    *,
    folder: Path,
    rx_ues: int,
    tx_ues: int,
    scenario: Scenario,
    mcs: Optional[MCS],
) -> Optional[Path]:
    for candidate in _build_filename_candidates(
        rx_ues=rx_ues,
        tx_ues=tx_ues,
        scenario=scenario,
        mcs=mcs,
    ):
        path = folder / candidate
        if path.exists():
            return path

    # Fallback: accept any prediction method when filenames differ.
    p1 = str(scenario.phase_1_enabled)
    p3 = str(scenario.phase_3_enabled)
    quant = str(scenario.quantization)
    mcs_globs = [""]
    if mcs:
        mcs_globs = [f"mod_order_{mcs.mod_order}_code_rate_{rate}_" for rate in mcs.code_rate_variants]
    for mcs_glob in mcs_globs:
        if scenario.prediction:
            pattern = (
                f"mu_mimo_results_p1_{p1}_p3_{p3}_{mcs_glob}rx_UE_{rx_ues}_tx_UE_{tx_ues}"
                f"_prediction_*_pmi_quantization_{quant}.npz"
            )
        else:
            pattern = (
                f"mu_mimo_results_p1_{p1}_p3_{p3}_{mcs_glob}rx_UE_{rx_ues}_tx_UE_{tx_ues}"
                f"_perfect_CSI_{scenario.perfect_csi}_pmi_quantization_{quant}.npz"
            )
        matches = sorted(folder.glob(pattern))
        if matches:
            return matches[0]
    return None

def _load_datapoint(path: Path) -> DataPoint:
    with np.load(path, allow_pickle=True) as data:
        return DataPoint(
            uncoded_ber=_nanmean_array(data, "uncoded_ber_list"),
            coded_ber=_nanmean_array(data, "ldpc_ber_list"),
            throughput=_scalar_last(data, "throughput"),
        )


def _mean_across_drops(
    *,
    base_dir: Path,
    mobility: str,
    drops: Sequence[int],
    rx_ues: int,
    tx_ues: int,
    scenario: Scenario,
    mcs: Optional[MCS] = None,
) -> Optional[DataPoint]:
    points: List[DataPoint] = []
    for drop in drops:
        folder = base_dir / f"channels_{mobility}_{drop}"
        path = _resolve_result_path(
            folder=folder,
            rx_ues=rx_ues,
            tx_ues=tx_ues,
            scenario=scenario,
            mcs=mcs,
        )
        if path is None:
            continue
        points.append(_load_datapoint(path))

    if not points:
        return None

    return DataPoint(
        uncoded_ber=float(np.nanmean([p.uncoded_ber for p in points])),
        coded_ber=float(np.nanmean([p.coded_ber for p in points])),
        throughput=float(np.nanmean([p.throughput for p in points])),
    )

def _best_throughput_point(
    *,
    base_dir: Path,
    mobility: str,
    drops: Sequence[int],
    rx_ues: int,
    tx_ues: int,
    scenario: Scenario,
    mcs_candidates: Sequence[MCS],
) -> Optional[DataPoint]:
    best_point: Optional[DataPoint] = None
    best_throughput = -float("inf")
    for mcs in mcs_candidates:
        point = _mean_across_drops(
            base_dir=base_dir,
            mobility=mobility,
            drops=drops,
            rx_ues=rx_ues,
            tx_ues=tx_ues,
            scenario=scenario,
            mcs=mcs,
        )
        if point is None or np.isnan(point.throughput):
            continue
        if point.throughput > best_throughput:
            best_throughput = point.throughput
            best_point = point
    return best_point


def _plot(
    *,
    x_values: Sequence[int],
    y_series: Sequence[tuple[str, Sequence[float]]],
    xlabel: str,
    ylabel: str,
    output_path: Path,
    semilogy: bool = False,
) -> None:
    plt.figure(figsize=(8, 5))
    markers = ["o", "s", "^", "D", "v", "P", "X"]
    for idx, (label, y) in enumerate(y_series):
        if semilogy:
            plt.semilogy(x_values, y, marker=markers[idx % len(markers)], label=label)
        else:
            plt.plot(x_values, y, marker=markers[idx % len(markers)], label=label)

    plt.xlabel(xlabel, fontsize=12)
    plt.ylabel(ylabel, fontsize=12)
    plt.grid(True, which="both", linestyle="--", alpha=0.4)
    plt.legend()
    plt.tight_layout()

    output_path.parent.mkdir(parents=True, exist_ok=True)
    base = output_path.with_suffix("")
    plt.savefig(base.with_suffix(".png"), dpi=250)
    plt.savefig(base.with_suffix(".svg"))
    plt.savefig(base.with_suffix(".eps"))
    print(f"Saved: {base.with_suffix('.png')}")


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--base-dir", type=Path, default=Path("results/channels_multiple_mu_mimo"))
    parser.add_argument("--mobility", default="high_mobility")
    parser.add_argument("--drops", type=int, nargs="+", default=[1, 2, 3])
    parser.add_argument("--rx-ues", type=int, nargs="+", default=[2, 3, 4])
    parser.add_argument("--tx-ues", type=int, nargs="+", default=[2, 4, 6, 8, 10])
    parser.add_argument("--fixed-rx", type=int, default=4)
    parser.add_argument("--fixed-tx", type=int, default=10)
    parser.add_argument("--output-dir", type=Path, default=Path("results"))
    parser.add_argument("--throughput-mod-orders", type=int, nargs="+", default=[2, 4])
    parser.add_argument(
        "--throughput-code-rates",
        nargs="+",
        default=["1/3", "1/2", "2/3"],
    )
    parser.add_argument("--ber-mod-order", type=int, default=4)
    parser.add_argument("--ber-code-rate", default="1/2")
    parser.add_argument(
        "--prediction-method",
        default="two_mode",
        help="Prediction method string used in filenames when prediction=True.",
    )
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    throughput_mcs = [
        MCS(mod_order=mod_order, code_rate=code_rate)
        for mod_order in args.throughput_mod_orders
        for code_rate in args.throughput_code_rates
    ]
    ber_mcs = MCS(mod_order=args.ber_mod_order, code_rate=args.ber_code_rate)

    scenarios = [
        # Scenario(
        #     phase_1_enabled=False,
        #     phase_3_enabled=True,
        #     prediction=False,
        #     quantization=True,
        #     perfect_csi=True,
        #     label="Perfect Phase-1 + Perfect CSI",
        # ),
        # Scenario(
        #     phase_1_enabled=False,
        #     phase_3_enabled=True,
        #     prediction=True,
        #     quantization=True,
        #     prediction_method=args.prediction_method,
        #     label="Perfect Phase-1 + Prediction",
        # ),
        Scenario(
            phase_1_enabled=True,
            phase_3_enabled=True,
            prediction=True,
            quantization=True,
            prediction_method=args.prediction_method,
            label="CJT",
        ),
    ]

    ber_vs_tx: List[tuple[str, List[float]]] = []
    tput_vs_tx: List[tuple[str, List[float]]] = []
    ber_vs_rx: List[tuple[str, List[float]]] = []
    tput_vs_rx: List[tuple[str, List[float]]] = []

    for scenario in scenarios:
        y_ber_tx: List[float] = []
        y_tput_tx: List[float] = []
        for tx in args.tx_ues:
            point = _mean_across_drops(
                base_dir=args.base_dir,
                mobility=args.mobility,
                drops=args.drops,
                rx_ues=args.fixed_rx,
                tx_ues=tx,
                scenario=scenario,
                mcs=ber_mcs,
            )
            y_ber_tx.append(point.coded_ber if point else float("nan"))
            best_point = _best_throughput_point(
                base_dir=args.base_dir,
                mobility=args.mobility,
                drops=args.drops,
                rx_ues=args.fixed_rx,
                tx_ues=tx,
                scenario=scenario,
                mcs_candidates=throughput_mcs,
            )
            y_tput_tx.append(best_point.throughput if best_point else float("nan"))

        y_ber_rx: List[float] = []
        y_tput_rx: List[float] = []
        for rx in args.rx_ues:
            point = _mean_across_drops(
                base_dir=args.base_dir,
                mobility=args.mobility,
                drops=args.drops,
                rx_ues=rx,
                tx_ues=args.fixed_tx,
                scenario=scenario,
                mcs=ber_mcs,
            )
            y_ber_rx.append(point.coded_ber if point else float("nan"))
            best_point = _best_throughput_point(
                base_dir=args.base_dir,
                mobility=args.mobility,
                drops=args.drops,
                rx_ues=rx,
                tx_ues=args.fixed_tx,
                scenario=scenario,
                mcs_candidates=throughput_mcs,
            )
            y_tput_rx.append(best_point.throughput if best_point else float("nan"))

        ber_vs_tx.append((scenario.label, y_ber_tx))
        tput_vs_tx.append((scenario.label, y_tput_tx))
        ber_vs_rx.append((scenario.label, y_ber_rx))
        tput_vs_rx.append((scenario.label, y_tput_rx))

    _plot(
        x_values=args.tx_ues,
        y_series=ber_vs_tx,
        xlabel="Tx UEs",
        ylabel="Coded BER",
        output_path=args.output_dir / "qtr4_coded_ber_vs_tx_ues.png",
        semilogy=True,
    )
    _plot(
        x_values=args.rx_ues,
        y_series=ber_vs_rx,
        xlabel="RX UEs",
        ylabel="Coded BER",
        output_path=args.output_dir / "qtr4_coded_ber_vs_rx_ues.png",
        semilogy=True,
    )
    _plot(
        x_values=args.tx_ues,
        y_series=tput_vs_tx,
        xlabel="Tx UEs",
        ylabel="Throughput (Mbps)",
        output_path=args.output_dir / "qtr4_throughput_vs_tx_ues.png",
    )
    _plot(
        x_values=args.rx_ues,
        y_series=tput_vs_rx,
        xlabel="RX UEs",
        ylabel="Throughput (Mbps)",
        output_path=args.output_dir / "qtr4_throughput_vs_rx_ues.png",
    )


if __name__ == "__main__":
    main()