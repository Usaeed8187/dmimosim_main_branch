"""Plot MU-MIMO throughput vs number of RUs for Phase-1 enabled/disabled.

This script is designed for artifacts generated by
``sims/wiopt_tput_across_tx_1_w_p1.sh``. It loads per-drop ``.npz`` files,
aggregates throughput across drops, and plots two curves:

* ``phase_1_enabled=True``
* ``phase_1_enabled=False``

By default, it expects files under ``results/channels_multiple_mu_mimo`` with
names like:

``mu_mimo_results_p1_<bool>_..._rx_UE_<rx>_tx_UE_<tx>_prediction_<method>_...``
"""

from __future__ import annotations

import argparse
from dataclasses import dataclass
from pathlib import Path
from typing import List, Sequence

import matplotlib.pyplot as plt
import numpy as np


@dataclass(frozen=True)
class Scenario:
    phase_1_enabled: bool
    label: str


def _load_throughput(npz_path: Path) -> float:
    """Load a scalar throughput value from an output artifact."""

    with np.load(npz_path, allow_pickle=True) as data:
        arr = np.asarray(data["throughput"]).reshape(-1)
        if arr.size == 0:
            return float("nan")
        return float(arr[-1])


def _build_filename(
    phase_1_enabled: bool,
    link_adapt: bool,
    rx_ues: int,
    tx_ues: int,
    perfect_csi: bool,
    prediction: bool,
    prediction_method: str,
    quantization: bool,
    modulation_order: int,
    code_rate: float,
) -> str:
    p1 = str(phase_1_enabled)
    quant = str(quantization)

    if link_adapt:
        mcs_part = "link_adapt"
    else:
        mcs_part = f"mod_order_{modulation_order}_code_rate_{code_rate}"

    if prediction:
        return (
            f"mu_mimo_results_p1_{p1}_{mcs_part}_rx_UE_{rx_ues}_tx_UE_{tx_ues}"
            f"_prediction_{prediction_method}_pmi_quantization_{quant}.npz"
        )

    return (
        f"mu_mimo_results_p1_{p1}_{mcs_part}_rx_UE_{rx_ues}_tx_UE_{tx_ues}"
        f"_perfect_CSI_{perfect_csi}_pmi_quantization_{quant}.npz"
    )


def _throughput_by_tx_ues(
    base_dir: Path,
    mobility: str,
    drops: Sequence[int],
    tx_ues_values: Sequence[int],
    scenario: Scenario,
    *,
    link_adapt: bool,
    rx_ues: int,
    perfect_csi: bool,
    prediction: bool,
    prediction_method: str,
    quantization: bool,
    modulation_order: int,
    code_rate: float,
) -> np.ndarray:
    """Average throughput across drops for each tx_ues value."""

    means: List[float] = []
    for tx_ues in tx_ues_values:
        per_drop: List[float] = []
        for drop in drops:
            folder = base_dir / f"channels_{mobility}_{drop}"
            filename = _build_filename(
                scenario.phase_1_enabled,
                link_adapt,
                rx_ues,
                tx_ues,
                perfect_csi,
                prediction,
                prediction_method,
                quantization,
                modulation_order,
                code_rate,
            )
            file_path = folder / filename
            if not file_path.exists():
                continue
            per_drop.append(_load_throughput(file_path))

        means.append(float(np.nanmean(per_drop)) if per_drop else float("nan"))

    return np.asarray(means, dtype=float)


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--base-dir",
        type=Path,
        default=Path("results/channels_multiple_mu_mimo"),
        help="Directory containing channels_<mobility>_<drop>/ subfolders.",
    )
    parser.add_argument("--mobility", default="high_mobility")
    parser.add_argument("--drops", type=int, nargs="+", default=[2, 3, 4, 5])
    parser.add_argument("--rx-ues", type=int, default=4)
    parser.add_argument("--tx-ues", type=int, nargs="+", default=[2, 4, 6, 8, 10])
    parser.add_argument("--link-adapt", action="store_true", default=True)
    parser.add_argument("--no-link-adapt", action="store_false", dest="link_adapt")
    parser.add_argument("--perfect-csi", action="store_true", default=False)
    parser.add_argument("--prediction", action="store_true", default=True)
    parser.add_argument("--no-prediction", action="store_false", dest="prediction")
    parser.add_argument("--prediction-method", default="two_mode")
    parser.add_argument("--quantization", action="store_true", default=True)
    parser.add_argument("--no-quantization", action="store_false", dest="quantization")
    parser.add_argument("--modulation-order", type=int, default=4)
    parser.add_argument("--code-rate", type=float, default=0.5)
    parser.add_argument(
        "--output",
        type=Path,
        default=Path("results/throughput_vs_rus_phase1_compare.png"),
    )
    return parser.parse_args()


def main() -> None:
    args = parse_args()

    scenarios = [
        Scenario(phase_1_enabled=True, label="Imperfect Phase 1"),
        Scenario(phase_1_enabled=False, label="Perfect Phase 1"),
    ]

    plt.figure(figsize=(8, 5))

    for scenario in scenarios:
        y = _throughput_by_tx_ues(
            args.base_dir,
            args.mobility,
            args.drops,
            args.tx_ues,
            scenario,
            link_adapt=args.link_adapt,
            rx_ues=args.rx_ues,
            perfect_csi=args.perfect_csi,
            prediction=args.prediction,
            prediction_method=args.prediction_method,
            quantization=args.quantization,
            modulation_order=args.modulation_order,
            code_rate=args.code_rate,
        )
        tx_ues = [x + 1 for x in args.tx_ues]
        plt.plot(tx_ues, y, marker="o", linewidth=2, label=scenario.label)

    plt.xlabel("Number of RUs", fontsize=14)
    plt.ylabel("Throughput (Mbps)", fontsize=14)
    # plt.title(
    #     f"Throughput vs RUs ({args.mobility}, rx_ues={args.rx_ues}, drops={args.drops})"
    # )
    plt.grid(True, linestyle="--", alpha=0.4)
    plt.legend()
    plt.tight_layout()

    args.output.parent.mkdir(parents=True, exist_ok=True)
    plt.savefig(args.output, dpi=200)
    plt.savefig("results/throughput_vs_rus_phase1_compare.eps")
    print(f"Saved plot to: {args.output}")


if __name__ == "__main__":
    main()